
import path from "node:path";
import fs from "node:fs/promises";
import ts from "typescript";
import sharp from "sharp";
import nextEnv from "@next/env";

const { loadEnvConfig } = nextEnv;

const ROOT = process.cwd();
loadEnvConfig(ROOT);

const SOURCE_FILE = path.join(ROOT, "lib", "photography.ts");
const BACKUP_FILE = `${SOURCE_FILE}.before-ai.bak`;
const PROGRESS_FILE = path.join(ROOT, "data", "photo-ai-progress.json");

const WAIT_BETWEEN_REQUESTS_MS = 5000;

if (!process.env.GROQ_API_KEY) {
  throw new Error("GROQ_API_KEY is missing. Add it to .env.local.");
}

// Reuse the existing Groq implementation and prompt.
const { generatePhotoMetadata } = await import(
  new URL("../lib/photo-metadata.ts", import.meta.url)
);

const sleep = (ms) =>
  new Promise((resolve) => setTimeout(resolve, ms));

async function exists(file) {
  try {
    await fs.access(file);
    return true;
  } catch {
    return false;
  }
}

function parsePhotographs(source) {
  const file = ts.createSourceFile(
    SOURCE_FILE,
    source,
    ts.ScriptTarget.Latest,
    true
  );

  let arrayNode;

  function visit(node) {
    if (
      ts.isVariableDeclaration(node) &&
      node.name.getText(file) === "photographs" &&
      node.initializer &&
      ts.isArrayLiteralExpression(node.initializer)
    ) {
      arrayNode = node.initializer;
    }

    ts.forEachChild(node, visit);
  }

  visit(file);

  if (!arrayNode) {
    throw new Error("Could not find the photographs array.");
  }

  return {
    file,
    photos: arrayNode.elements.filter(
      ts.isObjectLiteralExpression
    ),
  };
}

function propertyOf(object, key, file) {
  return object.properties.find(
    (property) =>
      ts.isPropertyAssignment(property) &&
      property.name.getText(file).replace(/^["']|["']$/g, "") === key
  );
}

function stringValue(object, key, file) {
  const property = propertyOf(object, key, file);

  if (!property || !ts.isStringLiteral(property.initializer)) {
    return "";
  }

  return property.initializer.text;
}

function updatePhotoSource(source, src, metadata) {
  const { file, photos } = parsePhotographs(source);

  const photo = photos.find(
    (item) => stringValue(item, "src", file) === src
  );

  if (!photo) {
    throw new Error(`Could not find ${src} in photography.ts`);
  }

  const edits = [];

  for (const [key, value] of Object.entries(metadata)) {
    const property = propertyOf(photo, key, file);
    const replacement = JSON.stringify(value);

    if (property) {
      edits.push({
        start: property.initializer.getStart(file),
        end: property.initializer.end,
        text: replacement,
      });
    } else {
      edits.push({
        start: photo.end - 1,
        end: photo.end - 1,
        text: `\n    ${key}: ${replacement},`,
      });
    }
  }

  edits.sort((a, b) => b.start - a.start);

  for (const edit of edits) {
    source =
      source.slice(0, edit.start) +
      edit.text +
      source.slice(edit.end);
  }

  return source;
}

async function readJson(file, fallback) {
  try {
    return JSON.parse(await fs.readFile(file, "utf8"));
  } catch {
    return fallback;
  }
}

async function main() {
  if (!(await exists(SOURCE_FILE))) {
    throw new Error(`Missing ${SOURCE_FILE}`);
  }

  // Preserve the original file once.
  if (!(await exists(BACKUP_FILE))) {
    await fs.copyFile(SOURCE_FILE, BACKUP_FILE);
    console.log(`Backup created: ${BACKUP_FILE}`);
  }

  let source = await fs.readFile(SOURCE_FILE, "utf8");

  let { photos } = parsePhotographs(source);

  const progress = await readJson(PROGRESS_FILE, {});
  const completed = new Set(Object.keys(progress));

  // Collections generated by previous successful requests.
  const existingCollections = [
    ...new Set(
      Object.values(progress)
        .map((item) => item.collection)
        .filter(
          (value) => typeof value === "string" && value.trim()
        )
    ),
  ];

  console.log(`Found ${photos.length} photographs.`);
  console.log(`Already completed: ${completed.size}.`);
  console.log("Pause between requests: 5 seconds.");

  for (let index = 0; index < photos.length; index++) {
    // Reparse because previous updates change source offsets.
    const parsed = parsePhotographs(source);
    const photo = parsed.photos[index];
    const src = stringValue(photo, "src", parsed.file);

    if (!src) {
      console.warn(`Skipping entry ${index + 1}: no src.`);
      continue;
    }

    if (completed.has(src)) {
      console.log(`[${index + 1}/${photos.length}] Already done: ${src}`);
      continue;
    }

    const imagePath = path.join(
      ROOT,
      "public",
      src.replace(/^\/+/, "")
    );

    if (!(await exists(imagePath))) {
      throw new Error(`Image file not found: ${imagePath}`);
    }

    console.log(`\n[${index + 1}/${photos.length}] ${src}`);

    // Resize large photographs before sending them to Groq.
    const imageBuffer = await sharp(imagePath)
      .rotate()
      .resize({
        width: 1600,
        height: 1600,
        fit: "inside",
        withoutEnlargement: true,
      })
      .jpeg({ quality: 85 })
      .toBuffer();

    let generated;

    try {
      // Existing helper generates title, collection and description.
      generated = await generatePhotoMetadata({
        image: imageBuffer,
        mimeType: "image/jpeg",
        title: "",
        collection: "",
        description: "",
        existingCollections,
      });
    } catch (error) {
      console.error(`Groq failed for ${src}:`, error);
      console.error("Completed photographs are saved. Rerun to resume.");
      process.exitCode = 1;
      return;
    }

    if (
      !generated.title?.trim() ||
      !generated.collection?.trim() ||
      !generated.description?.trim()
    ) {
      throw new Error(
        `Incomplete AI metadata for ${src}. Nothing was written for this photo.`
      );
    }

    const metadata = {
      title: generated.title.trim(),
      collection: generated.collection.trim(),
      description: generated.description.trim(),
    };

    source = updatePhotoSource(source, src, metadata);

    // Save immediately after every successful request.
    await fs.writeFile(SOURCE_FILE, source, "utf8");

    progress[src] = metadata;

    await fs.mkdir(path.dirname(PROGRESS_FILE), {
      recursive: true,
    });

    await fs.writeFile(
      PROGRESS_FILE,
      JSON.stringify(progress, null, 2),
      "utf8"
    );

    completed.add(src);

    // Make generated collections available to subsequent requests.
    if (
      !existingCollections.some(
        (item) =>
          item.toLowerCase() === metadata.collection.toLowerCase()
      )
    ) {
      existingCollections.push(metadata.collection);
    }

    console.log(`Title:       ${metadata.title}`);
    console.log(`Collection:  ${metadata.collection}`);
    console.log(`Description: ${metadata.description}`);
    console.log("Saved successfully.");

    // Five-second pause between API requests.
    if (index < photos.length - 1) {
      console.log("Waiting 5 seconds before next request...");
      await sleep(WAIT_BETWEEN_REQUESTS_MS);
    }
  }

  console.log("\nAll photographs processed.");
  console.log(`Updated: ${SOURCE_FILE}`);
  console.log(`Backup: ${BACKUP_FILE}`);
  console.log(`Progress: ${PROGRESS_FILE}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
